/**
 * shim：契约 §8 入口生成与校验。
 *
 * 覆盖：install 生成 6 个 0755 文件、check 通过 / 篡改一个字节后退 1 / 目录缺失退 1、
 * 二次 install 全部跳过、内容不同无 --force 退 1 有 --force 覆盖、
 * 桩包验证 -C → --root 与按文件名推导子命令、未知入口退 2、找不到包退 3、
 * 模板可被 bash 3.2 解析（bash -n 且不含 bash 4 语法）。
 * 桩测试 spawn 真实 bash，其余只调 runCli（注入输出流），不碰真实 gh/git。
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  utimesSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { runCli } from '../bin/cli.mjs'
import { SHIM_ENTRIES } from '../lib/shim.mjs'

const PKG = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const TEMPLATE = fileURLToPath(new URL('../templates/shim.sh', import.meta.url))
const HEADER = `# GENERATED by dsh-pipeline v${PKG.version} — do not edit. 源模板：templates/shim.sh`

function tmp() {
  return mkdtempSync(join(tmpdir(), 'dsh-shim-'))
}

function run(argv, deps = {}) {
  const state = { out: '', err: '' }
  const code = runCli(argv, {
    stdout: (text) => {
      state.out += text
    },
    stderr: (text) => {
      state.err += text
    },
    ...deps,
  })
  return { code, ...state }
}

function install(root, extra = []) {
  return run(['shim', 'install', '--root', root, ...extra])
}

function shimPath(root, file) {
  return join(root, 'scripts', 'pipeline', file)
}

function bash(script, args = []) {
  return spawnSync('bash', [script, ...args], { encoding: 'utf8', env: stubEnv() })
}

/** 桩测试不继承 DSH_PIPELINE_HOME，避免宿主环境把定位引到别处。 */
function stubEnv() {
  const env = { ...process.env }
  delete env.DSH_PIPELINE_HOME
  return env
}

test('shim install：生成 6 个 0755 文件，check 通过', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))

  const result = install(root)
  assert.equal(result.code, 0)
  assert.equal(result.err, '')
  const written = SHIM_ENTRIES.map((entry) => `写入: scripts/pipeline/${entry.file}\n`).join('')
  assert.equal(result.out, `${written}shim: 已生成 6 个入口\n`)

  for (const entry of SHIM_ENTRIES) {
    const file = shimPath(root, entry.file)
    assert.ok(existsSync(file), `${entry.file} 应存在`)
    assert.equal(statSync(file).mode & 0o777, 0o755, `${entry.file} 应为 0755`)
    const lines = readFileSync(file, 'utf8').split('\n')
    assert.equal(lines[0], HEADER, `${entry.file} 文件头应固定`)
  }
  // {{CMD}} 渲染进转发说明：new-task.sh 是 task，pipeline.sh 为空（透传）
  assert.match(readFileSync(shimPath(root, 'new-task.sh'), 'utf8'), /转发子命令: task/)
  assert.match(readFileSync(shimPath(root, 'pipeline.sh'), 'utf8'), /转发子命令: （空/)

  const checked = run(['shim', 'check', '--root', root])
  assert.equal(checked.code, 0)
  assert.equal(checked.out, 'shim: 6 个入口与模板一致\n')
  assert.equal(checked.err, '')
})

test('shim check：篡改一个字节 → 退 1，stderr 列出该文件', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))
  assert.equal(install(root).code, 0)

  const file = shimPath(root, 'status.sh')
  const original = readFileSync(file, 'utf8')
  writeFileSync(file, original.replace('set -euo pipefail', 'set -euo pipefail '), 'utf8')

  const result = run(['shim', 'check', '--root', root])
  assert.equal(result.code, 1)
  assert.equal(result.out, '')
  assert.equal(result.err, 'shim: 与模板不一致: status.sh\n')
})

test('shim check：入口目录不存在 → 退 1，提示先跑 shim install', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))

  const result = run(['shim', 'check', '--root', root])
  assert.equal(result.code, 1)
  assert.equal(result.out, '')
  assert.match(result.err, /不存在或不是目录，请先运行 shim install/)
})

test('shim install：二次运行全部跳过，不重写文件', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))
  assert.equal(install(root).code, 0)

  // 把 mtime 压到过去：二次 install 若重写文件，mtime 会回到当前时间
  const files = SHIM_ENTRIES.map((entry) => shimPath(root, entry.file))
  const past = new Date('2000-01-01T00:00:00Z')
  for (const file of files) utimesSync(file, past, past)

  const again = install(root)
  assert.equal(again.code, 0)
  assert.equal(again.err, '')
  assert.equal(again.out, 'shim: 已生成 6 个入口\n')
  for (const file of files) {
    assert.equal(statSync(file).mtimeMs, past.getTime(), `${file} 不应被重写`)
  }
})

test('shim install：内容不同无 --force 退 1，有 --force 覆盖', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))
  assert.equal(install(root).code, 0)

  const file = shimPath(root, 'review.sh')
  writeFileSync(file, '# 手改过的内容\n', 'utf8')

  const blocked = install(root)
  assert.equal(blocked.code, 1)
  assert.equal(blocked.out, '')
  assert.equal(blocked.err, 'shim: 已存在且内容不同: review.sh（确认后加 --force 覆盖）\n')
  assert.equal(readFileSync(file, 'utf8'), '# 手改过的内容\n', '拒绝时不许动磁盘')

  const forced = install(root, ['--force'])
  assert.equal(forced.code, 0)
  assert.equal(forced.err, '')
  assert.equal(forced.out, '写入: scripts/pipeline/review.sh\nshim: 已生成 6 个入口\n')
  assert.equal(run(['shim', 'check', '--root', root]).code, 0)
})

test('shim 入口：-C 翻成 --root，子命令按文件名推导（桩包）', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))

  // 桩包放在 <主工作区>/tools/node_modules/dsh-pipeline，cli 只打印收到的 argv
  const stub = join(root, 'tools', 'node_modules', 'dsh-pipeline', 'bin')
  mkdirSync(stub, { recursive: true })
  writeFileSync(
    join(stub, 'cli.mjs'),
    'console.log(process.argv.slice(2).join(" "))\n',
    'utf8',
  )
  assert.equal(install(root).code, 0)

  const newTask = shimPath(root, 'new-task.sh')
  const translated = bash(newTask, ['-C', '/tmp/x'])
  assert.equal(translated.status, 0, translated.stderr)
  assert.equal(translated.stdout, 'task --root /tmp/x\n')

  const inline = bash(newTask, ['-C=/tmp/y'])
  assert.equal(inline.status, 0, inline.stderr)
  assert.equal(inline.stdout, 'task --root /tmp/y\n')

  const positional = bash(newTask, ['42'])
  assert.equal(positional.status, 0, positional.stderr)
  assert.equal(positional.stdout, 'task 42\n')

  // pipeline.sh 不定子命令：第一个参数原样透传
  const pipeline = bash(shimPath(root, 'pipeline.sh'), ['status', '--root', '/tmp/z'])
  assert.equal(pipeline.status, 0, pipeline.stderr)
  assert.equal(pipeline.stdout, 'status --root /tmp/z\n')

  // 其余入口按文件名推导
  assert.equal(bash(shimPath(root, 'merge-pr.sh'), []).stdout, 'merge\n')
  assert.equal(bash(shimPath(root, 'status.sh'), []).stdout, 'status\n')
})

test('shim 入口：未知文件名 → 退 2 报未知入口', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))
  assert.equal(install(root).code, 0)

  const weird = shimPath(root, 'weird.sh')
  const generated = readFileSync(shimPath(root, 'new-task.sh'), 'utf8')
  writeFileSync(weird, generated, 'utf8')
  chmodSync(weird, 0o755)

  const result = bash(weird, [])
  assert.equal(result.status, 2)
  assert.equal(result.stdout, '')
  assert.match(result.stderr, /未知入口: weird\.sh/)
})

test('shim 入口：找不到共享包 → 退 3，stderr 列出试过的位置', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))
  assert.equal(install(root).code, 0)

  const result = bash(shimPath(root, 'new-task.sh'), [])
  assert.equal(result.status, 3)
  assert.equal(result.stdout, '')
  assert.match(result.stderr, /new-task\.sh: 找不到共享包 dsh-pipeline（试过 /)
  assert.ok(result.stderr.includes(join(root, 'tools/node_modules/dsh-pipeline/bin/cli.mjs')))
})

test('模板：bash -n 通过，且不含 bash 4 语法', () => {
  // macOS 上 /bin/bash 才是 3.2.57；走 PATH 可能拿到 Homebrew bash 5，测不出 3.2 兼容性
  const BASH = process.platform === 'darwin' ? '/bin/bash' : 'bash'
  const result = spawnSync(BASH, ['-n', TEMPLATE], { encoding: 'utf8' })
  assert.equal(result.status, 0, result.stderr)

  const template = readFileSync(TEMPLATE, 'utf8')
  assert.ok(!/declare[ \t]+-A/.test(template), '不得使用关联数组')
  assert.ok(!/\bmapfile\b/.test(template), '不得使用 mapfile')
  assert.ok(!/\breadarray\b/.test(template), '不得使用 readarray')
  assert.ok(!/\$\{[^}]*\^\^/.test(template), '不得使用 ${var^^}（bash 4）')
})

test('shim：缺动作 / 未知动作 / 未知选项 → 退 2', (t) => {
  const root = tmp()
  t.after(() => rmSync(root, { recursive: true, force: true }))

  const noAction = run(['shim'])
  assert.equal(noAction.code, 2)
  assert.match(noAction.err, /用法: dsh-pipeline shim/)

  const unknown = run(['shim', 'frobnicate'])
  assert.equal(unknown.code, 2)
  assert.match(unknown.err, /未知动作: frobnicate/)

  const unknownFlag = run(['shim', 'install', '--bogus'])
  assert.equal(unknownFlag.code, 2)
  assert.match(unknownFlag.err, /未知选项: --bogus/)

  // check 不接受 --force：严格解析，不静默忽略
  const forceOnCheck = run(['shim', 'check', '--force'])
  assert.equal(forceOnCheck.code, 2)
  assert.match(forceOnCheck.err, /未知选项: --force/)
})
