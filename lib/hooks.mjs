/**
 * pre-push 钩子的生成、安装与校验。
 *
 * 单一事实源在这里：钩子正文（含标记行）、目标路径推算、install 的
 * 「新建 / 幂等 / 覆盖 / 拒绝」判定、check 的逐字节比对。
 * CLI 只做参数编排与打印，不复制任何判定逻辑。
 *
 * 目标路径必须从 `git rev-parse --git-common-dir` 推：linked worktree 里
 * `.git` 是文件而不是目录，钩子装进 worktree 自己的 git 目录根本不生效，
 * 主仓 git 目录那一份才是所有 worktree 共用的。git 返回的相对路径按 root 拼成绝对路径。
 *
 * 退出码口径（由 CLI 透传）：0 成功 / 1 业务拒绝（未装、不一致、拒绝覆盖）/ 2 环境错误。
 */
import { chmodSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, isAbsolute, join, resolve } from 'node:path'

import { configGet, gitCommonDir } from './git.mjs'

/** 本工具安装的标记行：带它才允许覆盖，check 也据此识别自家文件。 */
export const HOOK_MARKER = '# GENERATED by dsh-pipeline hooks install — do not edit'

/** 拦截直推的正文：remote_ref 是 main / master 就拒绝，其余放行。 */
const INTERCEPT_BODY = `#!/usr/bin/env bash
${HOOK_MARKER}
#
# 拦截直推 main / master 的 pre-push 钩子。
# git 约定：stdin 每行 = <local_ref> <local_sha> <remote_ref> <remote_sha>。
# macOS 自带 bash 3.2：不用 bash 4 语法，默认值一律用 if 判断。

set -u

REJECT=""
while read -r LOCAL_REF LOCAL_SHA REMOTE_REF REMOTE_SHA; do
  if [ -z "\${REMOTE_REF-}" ]; then continue; fi
  if [ "\${REMOTE_REF}" = "refs/heads/main" ] || [ "\${REMOTE_REF}" = "refs/heads/master" ]; then
    REJECT="\${REMOTE_REF}"
    break
  fi
done

if [ -z "\${REJECT}" ]; then
  exit 0
fi

echo "✗ 拒绝直推 \${REJECT}：改动必须走 issue → task 分支 → PR → 审核 → squash 合并，不接受直推。" >&2
exit 1
`

/** `--allow-main` 版本：不拦截任何推送，只保留标记行（用于确实需要直推的仓）。 */
const ALLOW_MAIN_BODY = `#!/usr/bin/env bash
${HOOK_MARKER}
#
# 允许直推版本（hooks install --allow-main 生成）：不拦截任何推送。

exit 0
`

/** 用当前包内容渲染钩子正文。 */
export function renderHook({ allowMain = false } = {}) {
  return allowMain === true ? ALLOW_MAIN_BODY : INTERCEPT_BODY
}

/** 主仓 git 目录下的 hooks/pre-push 绝对路径。 */
function hookTarget(root, { runner } = {}) {
  const common = gitCommonDir(root, { runner })
  if (!common.ok) return { ok: false, error: common.error }
  const text = String(common.data ?? '').trim()
  if (text.length === 0) return { ok: false, error: 'git 未返回公共 git 目录' }
  const base = isAbsolute(text) ? text : resolve(root, text)
  // core.hooksPath（husky 等会设置）：设了就往那里装，否则装进 .git/hooks 会静默不生效
  const custom = configGet(root, 'core.hooksPath', { runner })
  const customPath = custom.ok ? String(custom.data ?? '').trim() : ''
  if (customPath.length > 0) {
    const hookDir = isAbsolute(customPath) ? customPath : resolve(root, customPath)
    return { ok: true, path: join(hookDir, 'pre-push'), hooksPath: customPath }
  }
  return { ok: true, path: join(base, 'hooks', 'pre-push') }
}

function readIfExists(path) {
  if (!existsSync(path)) return { ok: true, data: null }
  try {
    return { ok: true, data: readFileSync(path, 'utf8') }
  } catch (error) {
    return { ok: false, error: error instanceof Error ? error.message : String(error) }
  }
}

/**
 * hooks install：把 pre-push 钩子写进主仓 git 目录的 hooks/。
 *
 * 判定顺序：不存在 → 新建；内容相同 → 幂等（只补权限）；内容不同但带标记行
 * （本工具的旧版本 / 被改过的自家文件）→ 覆盖；带 --force → 覆盖；
 * 其余（别人的钩子）→ 拒绝，交调用方退 1。
 * @returns {{ ok: true, status: 'installed'|'updated'|'unchanged', path: string }
 *          | { ok: false, code: 1|2, path?: string, error: string }}
 */
export function installHook(root, { force = false, allowMain = false, runner } = {}) {
  const target = hookTarget(root, { runner })
  if (!target.ok) return { ok: false, code: 2, error: `无法定位 git 目录: ${target.error}` }

  const content = renderHook({ allowMain })
  const existing = readIfExists(target.path)
  if (!existing.ok) {
    return { ok: false, code: 2, path: target.path, error: `读取已有钩子失败: ${existing.error}` }
  }

  let status = 'installed'
  if (existing.data !== null) {
    if (existing.data === content) status = 'unchanged'
    else if (existing.data.includes(HOOK_MARKER)) status = 'updated'
    else if (force === true) status = 'updated'
    else {
      return {
        ok: false,
        code: 1,
        path: target.path,
        error: `已存在且不是本工具安装的钩子（没有标记行）: ${target.path}（确认后加 --force 覆盖）`,
      }
    }
  }

  try {
    if (status !== 'unchanged') {
      mkdirSync(dirname(target.path), { recursive: true })
      writeFileSync(target.path, content, { mode: 0o755 })
    }
    // umask 会吃掉 writeFileSync 的 mode，显式 chmod 一次保证 0755
    chmodSync(target.path, 0o755)
  } catch (error) {
    return {
      ok: false,
      code: 2,
      path: target.path,
      error: `写入钩子失败: ${error instanceof Error ? error.message : String(error)}`,
    }
  }
  return { ok: true, status, path: target.path }
}

/**
 * hooks check：已装钩子与本包当前版本生成的内容逐字节比对。
 * 两种变体（默认拦截版 / --allow-main 放行版）都算「本包生成的内容」——
 * 都是当前版本渲染出来的，改用别的版本或被手改过才算漂移。
 * @returns {{ ok: true, path: string }
 *          | { ok: false, code: 1|2, reason?: 'missing'|'mismatch', path?: string, error: string }}
 */
export function checkHook(root, { runner } = {}) {
  const target = hookTarget(root, { runner })
  if (!target.ok) return { ok: false, code: 2, error: `无法定位 git 目录: ${target.error}` }

  const existing = readIfExists(target.path)
  if (!existing.ok) {
    return { ok: false, code: 2, path: target.path, error: `读取钩子失败: ${existing.error}` }
  }
  if (existing.data === null) {
    return {
      ok: false,
      code: 1,
      reason: 'missing',
      path: target.path,
      error: `未安装 pre-push 钩子: ${target.path}，请先运行 hooks install`,
    }
  }

  const contentMatches =
    existing.data === renderHook() || existing.data === renderHook({ allowMain: true })
  // 内容对但被 chmod -x：钩子根本不会跑，check 报「一致」就是假绿
  let executable = true
  try {
    executable = (statSync(target.path).mode & 0o111) !== 0
  } catch {
    executable = false
  }
  if (contentMatches && !executable) {
    return {
      ok: false,
      code: 1,
      reason: 'not-executable',
      path: target.path,
      error: `钩子没有可执行位，git 不会运行它: ${target.path}（请重新运行 hooks install）`,
    }
  }
  const matches = contentMatches
  if (!matches) {
    return {
      ok: false,
      code: 1,
      reason: 'mismatch',
      path: target.path,
      error: `钩子与本包生成的内容不一致: ${target.path}（请重新运行 hooks install）`,
    }
  }
  return { ok: true, path: target.path }
}
